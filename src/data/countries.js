/**
 * Returns flag image URL for a given 2-letter country code
 * FlagCDN provides fast, reliable, SVG & PNG flags
 */
export function getFlagUrl(code, format = 'png', width = 320) {
  if (!code) return '';
  const lower = code.toLowerCase();
  if (format === 'svg') {
    return `https://flagcdn.com/${lower}.svg`;
  }
  return `https://flagcdn.com/w${width}/${lower}.png`;
}

